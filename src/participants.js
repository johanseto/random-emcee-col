const competitionNames = {
    colombia: "Colombia",
    internacional: "Internacional",
}

const getCompetitionRosters = (competition) => {
    if (!Object.hasOwn(rosters, competition)) {
        throw new RangeError(`Competencia desconocida: ${competition}`)
    }

    return rosters[competition]
}

const getAvailableYears = (competition) => {
    const competitionRosters = getCompetitionRosters(competition)
    return Object.keys(competitionRosters).sort((a, b) => Number(a) - Number(b))
}

const getParticipants = (competition, year) => {
    const competitionRosters = getCompetitionRosters(competition)
    const yearKey = String(year).trim()

    if (!Object.hasOwn(competitionRosters, yearKey)) {
        const years = getAvailableYears(competition).join(", ")
        throw new RangeError(
            `No hay participantes de Red Bull Batalla ${competitionNames[competition]} para ${yearKey}. Años disponibles: ${years}`,
        )
    }

    return [...competitionRosters[yearKey]]
}

module.exports = { getAvailableYears, getParticipants }
